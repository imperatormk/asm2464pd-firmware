/*=== Sequences ===*/

static void usb4_lane_phy(void) {
  usb4_lane_block(usb4_lane_phy_1, USB4_N(usb4_lane_phy_1));
  x_mod(REG_ADDR(REG_PHY_CTRL_C21D), 0x40, 0x80);
  usb4_lane_block(usb4_lane_phy_2, USB4_N(usb4_lane_phy_2));
  usb4_lane_pairs(usb4_lane_phy_3, USB4_N(usb4_lane_phy_3));
  usb4_lane_block(usb4_lane_phy_4, USB4_N(usb4_lane_phy_4));
  usb4_lane_block(usb4_lane_phy_5, USB4_N(usb4_lane_phy_5));
  usb4_lane_block(usb4_lane_phy_6, USB4_N(usb4_lane_phy_6));
  usb4_lane_pairs(usb4_lane_phy_7, USB4_N(usb4_lane_phy_7));
}

static void usb4_seq_lanephy(void) {
  usb4_run_ops(usb4_tab_lane_prep, USB4_N(usb4_tab_lane_prep));
  x_mod(REG_ADDR(REG_CPU_CLK_CFG), 0x60, 0x80);
  x_mod(REG_ADDR(REG_PHY_CTRL_C21F), 0x00, 0x04);
  bank1_wr(0x2849, 0xA0);
  usb4_lane_phy();
}

static void usb4_seq_bootrest(void) {
  usb4_run_ops(usb4_tab_boot_pre, USB4_N(usb4_tab_boot_pre));
  usb4_run_ops(usb4_tab_boot_post, USB4_N(usb4_tab_boot_post));
}

